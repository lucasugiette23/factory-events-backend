package com.factory.events.config;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import javax.sql.DataSource;

final class H2SchemaMigration {
    private H2SchemaMigration() {
    }

    static void migrate(DataSource dataSource) throws SQLException {
        try (Connection connection = dataSource.getConnection()) {
            if (!"H2".equals(connection.getMetaData().getDatabaseProductName())) {
                return;
            }
            try (var tables = connection.getMetaData().getTables(null, "PUBLIC", "EVENTS", null)) {
                if (!tables.next()) {
                    return;
                }
            }
            List<String> primaryKey = new ArrayList<>();
            try (var keys = connection.getMetaData().getPrimaryKeys(null, "PUBLIC", "EVENTS")) {
                while (keys.next()) {
                    primaryKey.add(keys.getString("COLUMN_NAME"));
                }
            }
            boolean hasLegacyKey;
            try (var columns = connection.getMetaData().getColumns(null, "PUBLIC", "EVENTS", "IDEMPOTENCY_KEY")) {
                hasLegacyKey = columns.next();
            }
            if (primaryKey.equals(List.of("ID")) && !hasLegacyKey) {
                return;
            }
            try (var statement = connection.createStatement()) {
                statement.execute("ALTER TABLE events ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY");
                if (!primaryKey.equals(List.of("ID"))) {
                    statement.execute("ALTER TABLE events DROP CONSTRAINT IF EXISTS uk_events_event_id");
                    if (!primaryKey.isEmpty()) {
                        statement.execute("ALTER TABLE events DROP PRIMARY KEY");
                    }
                    statement.execute("ALTER TABLE events ADD PRIMARY KEY(id)");
                }
                statement.execute("ALTER TABLE events ADD CONSTRAINT IF NOT EXISTS uk_events_event_id UNIQUE(event_id)");
                statement.execute("ALTER TABLE events DROP CONSTRAINT IF EXISTS uk_events_idempotency_key");
                statement.execute("ALTER TABLE events DROP COLUMN IF EXISTS idempotency_key");
            }
        }
    }
}
